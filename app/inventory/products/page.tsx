"use client";

import { useCallback, useEffect, useState, useMemo } from "react";
import Link from "next/link";
import { supabase } from "@/lib/supabase";
import { getCompanyId, fmtAED } from "@/lib/helpers";
import {
  getMaterialsList,
  saveMaterialMaster,
  getCompanyInventorySettings,
  saveCompanyInventorySettings,
  getProductMovementHistory,
  executeQuickStockAdjustment,
  type MaterialItem,
  type ProductType,
  type CustomCategory,
  type CustomUnit,
  type CustomFieldDefinition,
  type CustomFieldType,
  type CompanyInventorySettings,
  type MaterialMovementRecord,
  DEFAULT_CUSTOM_CATEGORIES,
  DEFAULT_CUSTOM_UNITS,
} from "@/lib/materialInventory";
import {
  Package,
  Plus,
  Search,
  Filter,
  CheckCircle2,
  AlertTriangle,
  Pencil,
  Power,
  ArrowLeft,
  Loader2,
  Layers,
  ChevronDown,
  ChevronUp,
  History,
  ArrowDownLeft,
  ArrowUpRight,
  X,
  Settings2,
  Trash2,
  Tag,
  Ruler,
  Boxes,
  Briefcase,
  AlertCircle,
  ExternalLink,
} from "lucide-react";

type ProductDraft = {
  id?: string;
  name: string;
  category: string;
  unit: string;
  selling_price: string;
  product_type: ProductType;
  // More options
  sku: string;
  cost_price: string;
  vat_rate: string;
  opening_stock: string;
  minimum_stock: string;
  supplier_name: string;
  description: string;
  notes: string;
  active: boolean;
  custom_field_values: Record<string, string | number | boolean>;
};

const emptyProductDraft: ProductDraft = {
  name: "",
  category: "PVC Fabric",
  unit: "PCS",
  selling_price: "",
  product_type: "material",
  sku: "",
  cost_price: "",
  vat_rate: "5",
  opening_stock: "0",
  minimum_stock: "0",
  supplier_name: "",
  description: "",
  notes: "",
  active: true,
  custom_field_values: {},
};

export default function MaterialProductsPage() {
  const [companyId, setCompanyId] = useState("");
  const [materials, setMaterials] = useState<MaterialItem[]>([]);
  const [settings, setSettings] = useState<CompanyInventorySettings>({
    categories: DEFAULT_CUSTOM_CATEGORIES,
    units: DEFAULT_CUSTOM_UNITS,
    custom_fields: [],
  });

  // Filters & Search
  const [search, setSearch] = useState("");
  const [typeFilter, setTypeFilter] = useState<"all" | ProductType>("all");
  const [categoryFilter, setCategoryFilter] = useState<string>("all");
  const [statusFilter, setStatusFilter] = useState<"all" | "active" | "inactive">("active");

  // Loading & Notifications
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [togglingId, setTogglingId] = useState<string | null>(null);
  const [notice, setNotice] = useState<{ type: "success" | "error"; text: string } | null>(null);

  // Modals state
  const [showProductModal, setShowProductModal] = useState(false);
  const [showMoreOptions, setShowMoreOptions] = useState(false);
  const [draft, setDraft] = useState<ProductDraft>(emptyProductDraft);
  const [skuAutoGenerated, setSkuAutoGenerated] = useState(false);

  // Customization Modals
  const [showCategoryModal, setShowCategoryModal] = useState(false);
  const [newCatName, setNewCatName] = useState("");
  const [newCatColor, setNewCatColor] = useState("#3B82F6");

  const [showUnitModal, setShowUnitModal] = useState(false);
  const [newUnitCode, setNewUnitCode] = useState("");
  const [newUnitName, setNewUnitName] = useState("");

  const [showCustomFieldModal, setShowCustomFieldModal] = useState(false);
  const [newFieldName, setNewFieldName] = useState("");
  const [newFieldType, setNewFieldType] = useState<CustomFieldType>("text");
  const [newFieldRequired, setNewFieldRequired] = useState(false);
  const [newFieldDefault, setNewFieldDefault] = useState("");
  const [newFieldOptions, setNewFieldOptions] = useState("");

  // Movement History Modal
  const [showHistoryModal, setShowHistoryModal] = useState(false);
  const [historyProduct, setHistoryProduct] = useState<MaterialItem | null>(null);
  const [historyMovements, setHistoryMovements] = useState<MaterialMovementRecord[]>([]);
  const [historyLoading, setHistoryLoading] = useState(false);

  // Quick Stock Adjustment Modal
  const [stockModalType, setStockModalType] = useState<"IN" | "OUT" | null>(null);
  const [stockModalProduct, setStockModalProduct] = useState<MaterialItem | null>(null);
  const [stockModalQty, setStockModalQty] = useState("");
  const [stockModalReason, setStockModalReason] = useState("");
  const [stockModalSubmitting, setStockModalSubmitting] = useState(false);

  const refreshAll = useCallback(async (cId: string) => {
    try {
      const prodList = await getMaterialsList(cId);
      setMaterials(prodList);
      const invSettings = await getCompanyInventorySettings(cId, prodList);
      setSettings(invSettings);
    } catch (err) {
      console.error("Failed to load inventory data:", err);
      setNotice({ type: "error", text: "Unable to load products and settings from database." });
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    let active = true;
    getCompanyId().then(async (id) => {
      if (!active) return;
      if (!id) {
        setNotice({ type: "error", text: "Please select a company before managing products." });
        setLoading(false);
        return;
      }
      setCompanyId(id);
      await refreshAll(id);
    });
    return () => {
      active = false;
    };
  }, [refreshAll]);

  // Auto-dismiss notice after 5 seconds
  useEffect(() => {
    if (!notice) return;
    const timer = setTimeout(() => setNotice(null), 5000);
    return () => clearTimeout(timer);
  }, [notice]);

  // Filtered Products
  const filteredProducts = useMemo(() => {
    const q = search.trim().toLowerCase();
    return materials.filter((item) => {
      // Status filter
      if (statusFilter === "active" && !item.active) return false;
      if (statusFilter === "inactive" && item.active) return false;

      // Type filter
      if (typeFilter !== "all" && item.product_type !== typeFilter) return false;

      // Category filter
      if (categoryFilter !== "all" && item.category !== categoryFilter) return false;

      // Search query
      if (q) {
        const matchName = item.name.toLowerCase().includes(q);
        const matchSku = item.sku?.toLowerCase().includes(q) || false;
        const matchCategory = item.category.toLowerCase().includes(q);
        const matchSupplier = item.supplier_name?.toLowerCase().includes(q) || false;
        const matchDesc = item.description?.toLowerCase().includes(q) || false;
        if (!matchName && !matchSku && !matchCategory && !matchSupplier && !matchDesc) return false;
      }

      return true;
    });
  }, [materials, search, typeFilter, categoryFilter, statusFilter]);

  // Product Counts
  const counts = useMemo(() => {
    const total = materials.length;
    const active = materials.filter((m) => m.active).length;
    const inactive = total - active;
    const lowStock = materials.filter(
      (m) => !m.is_service && m.minimum_stock > 0 && m.current_stock <= m.minimum_stock
    ).length;
    return { total, active, inactive, lowStock };
  }, [materials]);

  // Generate clean SKU suggestion
  function generateSuggestedSku(name: string, type: ProductType): string {
    const prefix = type === "service" ? "SRV" : type === "finished_product" ? "FP" : "MAT";
    const cleanName = name.replace(/[^a-zA-Z0-9]/g, "").slice(0, 4).toUpperCase();
    const randomSuffix = Math.floor(100 + Math.random() * 900);
    return cleanName ? `${prefix}-${cleanName}-${randomSuffix}` : `${prefix}-${randomSuffix}`;
  }

  // Open Add Product Modal
  function handleOpenAddProduct() {
    const defaultCat = settings.categories.find((c) => c.active)?.name || "PVC Fabric";
    const defaultUnit = settings.units.find((u) => u.active)?.code || "PCS";
    setDraft({
      ...emptyProductDraft,
      category: defaultCat,
      unit: defaultUnit,
      custom_field_values: {},
    });
    setShowMoreOptions(false);
    setSkuAutoGenerated(false);
    setShowProductModal(true);
  }

  // Open Edit Product Modal
  function handleOpenEditProduct(item: MaterialItem) {
    setDraft({
      id: item.id,
      name: item.name,
      category: item.category,
      unit: item.unit,
      selling_price: item.selling_price > 0 ? String(item.selling_price) : "",
      product_type: item.product_type,
      sku: item.sku || "",
      cost_price: item.cost_price > 0 ? String(item.cost_price) : "",
      vat_rate: String(item.vat_rate ?? 5),
      opening_stock: String(item.current_stock || 0),
      minimum_stock: item.minimum_stock > 0 ? String(item.minimum_stock) : "",
      supplier_name: item.supplier_name || "",
      description: item.description || "",
      notes: item.notes || "",
      active: item.active,
      custom_field_values: item.custom_field_values || {},
    });
    setShowMoreOptions(true);
    setSkuAutoGenerated(false);
    setShowProductModal(true);
  }

  // Save Product (Create or Update)
  async function handleSaveProduct(e: React.FormEvent) {
    e.preventDefault();
    if (!companyId) return;

    const trimmedName = draft.name.trim();
    if (!trimmedName) {
      setNotice({ type: "error", text: "Product / Material Name is required." });
      return;
    }

    setSaving(true);
    try {
      const parsedCost = parseFloat(draft.cost_price) || 0;
      const parsedSelling = parseFloat(draft.selling_price) || 0;
      const parsedVat = parseFloat(draft.vat_rate) || 5;
      const parsedMinStock = parseFloat(draft.minimum_stock) || 0;
      const parsedOpeningStock = parseFloat(draft.opening_stock) || 0;

      const payload: Partial<MaterialItem> = {
        id: draft.id,
        company_id: companyId,
        name: trimmedName,
        category: draft.category || "Other",
        unit: draft.unit || "PCS",
        product_type: draft.product_type,
        sku: draft.sku.trim() || null,
        cost_price: Math.max(0, parsedCost),
        selling_price: Math.max(0, parsedSelling),
        vat_rate: Math.max(0, parsedVat),
        minimum_stock: draft.product_type === "service" ? 0 : Math.max(0, parsedMinStock),
        supplier_name: draft.supplier_name.trim() || null,
        description: draft.description.trim() || null,
        notes: draft.notes.trim() || null,
        active: draft.active,
        custom_field_values: draft.custom_field_values,
      };

      await saveMaterialMaster(
        companyId,
        payload,
        draft.id ? 0 : parsedOpeningStock
      );

      setNotice({
        type: "success",
        text: draft.id
          ? `Product "${trimmedName}" updated successfully.`
          : `Product "${trimmedName}" created successfully.`,
      });

      setShowProductModal(false);
      await refreshAll(companyId);
    } catch (err) {
      setNotice({
        type: "error",
        text: err instanceof Error ? err.message : "Failed to save product.",
      });
    } finally {
      setSaving(false);
    }
  }

  // Toggle Active / Inactive
  async function handleToggleStatus(item: MaterialItem) {
    if (!companyId) return;
    const nextState = !item.active;
    if (!nextState) {
      const confirmDeactivate = window.confirm(
        `Are you sure you want to deactivate "${item.name}"?\n\nDeactivated products will not appear in active document creation, but all historical invoices, quotations, and stock movements will remain preserved.`
      );
      if (!confirmDeactivate) return;
    }

    setTogglingId(item.id);
    try {
      await supabase
        .from("products")
        .update({ active: nextState, updated_at: new Date().toISOString() })
        .eq("id", item.id)
        .eq("company_id", companyId);

      setMaterials((prev) =>
        prev.map((p) => (p.id === item.id ? { ...p, active: nextState } : p))
      );
      setNotice({
        type: "success",
        text: `Product "${item.name}" is now ${nextState ? "Active" : "Deactivated"}.`,
      });
    } catch (err) {
      setNotice({
        type: "error",
        text: err instanceof Error ? err.message : "Failed to update product status.",
      });
    } finally {
      setTogglingId(null);
    }
  }

  // Open Movement History Modal
  async function handleOpenHistory(item: MaterialItem) {
    setHistoryProduct(item);
    setHistoryLoading(true);
    setShowHistoryModal(true);
    try {
      const moves = await getProductMovementHistory(companyId, item.id);
      setHistoryMovements(moves);
    } catch {
      setHistoryMovements([]);
    } finally {
      setHistoryLoading(false);
    }
  }

  // Open Quick Stock Modal
  function handleOpenStockModal(type: "IN" | "OUT", item?: MaterialItem) {
    setStockModalType(type);
    setStockModalProduct(item || materials.find((m) => !m.is_service) || null);
    setStockModalQty("");
    setStockModalReason("");
  }

  // Execute Quick Stock Adjustment
  async function handleExecuteStockAdjustment(e: React.FormEvent) {
    e.preventDefault();
    if (!companyId || !stockModalProduct || !stockModalType) return;
    const parsedQty = parseFloat(stockModalQty);
    if (isNaN(parsedQty) || parsedQty <= 0) {
      setNotice({ type: "error", text: "Please enter a valid quantity greater than zero." });
      return;
    }

    setStockModalSubmitting(true);
    try {
      const res = await executeQuickStockAdjustment(
        companyId,
        stockModalProduct.id,
        stockModalType,
        parsedQty,
        stockModalReason || `Quick Stock ${stockModalType}`
      );

      setNotice({
        type: "success",
        text: `Stock ${stockModalType === "IN" ? "received" : "dispatched"} for ${stockModalProduct.name} (${parsedQty} ${stockModalProduct.unit}). Reference: ${res.docNumber}.`,
      });

      setStockModalType(null);
      await refreshAll(companyId);
    } catch (err) {
      setNotice({
        type: "error",
        text: err instanceof Error ? err.message : "Failed to record stock movement.",
      });
    } finally {
      setStockModalSubmitting(false);
    }
  }

  // Category Management Handlers
  async function handleAddCategory(e: React.FormEvent) {
    e.preventDefault();
    const clean = newCatName.trim();
    if (!clean) return;

    if (settings.categories.some((c) => c.name.toLowerCase() === clean.toLowerCase())) {
      alert("A category with this name already exists.");
      return;
    }

    const updatedCategories: CustomCategory[] = [
      ...settings.categories,
      {
        id: `cat-${Date.now()}`,
        name: clean,
        color: newCatColor,
        active: true,
        is_default: false,
      },
    ];

    const updatedSettings = { ...settings, categories: updatedCategories };
    setSettings(updatedSettings);
    await saveCompanyInventorySettings(companyId, updatedSettings);
    setNewCatName("");
  }

  async function handleToggleCategory(catId: string) {
    const target = settings.categories.find((c) => c.id === catId);
    if (!target) return;

    // Check if category is used by existing products
    if (target.active) {
      const usageCount = materials.filter(
        (m) => m.category.toLowerCase().trim() === target.name.toLowerCase().trim()
      ).length;
      if (usageCount > 0) {
        alert(
          `Cannot deactivate category "${target.name}": It is currently used by ${usageCount} product(s). Please reassign those products before deactivating.`
        );
        return;
      }
    }

    const updatedCategories = settings.categories.map((c) =>
      c.id === catId ? { ...c, active: !c.active } : c
    );
    const updatedSettings = { ...settings, categories: updatedCategories };
    setSettings(updatedSettings);
    await saveCompanyInventorySettings(companyId, updatedSettings);
  }

  // Unit Management Handlers
  async function handleAddUnit(e: React.FormEvent) {
    e.preventDefault();
    const code = newUnitCode.trim().toUpperCase();
    const name = newUnitName.trim() || code;
    if (!code) return;

    if (settings.units.some((u) => u.code.toUpperCase() === code)) {
      alert(`Unit with code "${code}" already exists.`);
      return;
    }

    const updatedUnits: CustomUnit[] = [
      ...settings.units,
      { code, name, active: true, is_default: false },
    ];
    const updatedSettings = { ...settings, units: updatedUnits };
    setSettings(updatedSettings);
    await saveCompanyInventorySettings(companyId, updatedSettings);
    setNewUnitCode("");
    setNewUnitName("");
  }

  async function handleToggleUnit(code: string) {
    const updatedUnits = settings.units.map((u) =>
      u.code === code ? { ...u, active: !u.active } : u
    );
    const updatedSettings = { ...settings, units: updatedUnits };
    setSettings(updatedSettings);
    await saveCompanyInventorySettings(companyId, updatedSettings);
  }

  // Custom Field Management Handlers
  async function handleAddCustomField(e: React.FormEvent) {
    e.preventDefault();
    const name = newFieldName.trim();
    if (!name) return;
    const key = name.toLowerCase().replace(/[^a-z0-9]/g, "_").slice(0, 30);

    if (settings.custom_fields.some((f) => f.key === key)) {
      alert("A custom field with this name already exists.");
      return;
    }

    const parsedOptions =
      newFieldType === "dropdown"
        ? newFieldOptions
            .split(",")
            .map((o) => o.trim())
            .filter(Boolean)
        : undefined;

    const newField: CustomFieldDefinition = {
      id: `field-${Date.now()}`,
      name,
      key,
      type: newFieldType,
      required: newFieldRequired,
      default_value: newFieldDefault.trim() || undefined,
      options: parsedOptions,
      active: true,
    };

    const updatedFields = [...settings.custom_fields, newField];
    const updatedSettings = { ...settings, custom_fields: updatedFields };
    setSettings(updatedSettings);
    await saveCompanyInventorySettings(companyId, updatedSettings);

    // Apply default to current draft if adding from product modal
    setDraft((prev) => ({
      ...prev,
      custom_field_values: {
        ...prev.custom_field_values,
        [key]: newFieldDefault.trim() || "",
      },
    }));

    setNewFieldName("");
    setNewFieldDefault("");
    setNewFieldOptions("");
    setShowCustomFieldModal(false);
  }

  return (
    <main className="min-h-screen bg-slate-900 text-slate-100 pb-16">
      {/* Header */}
      <header className="sticky top-0 z-30 border-b border-slate-800 bg-slate-950/80 backdrop-blur-md">
        <div className="mx-auto flex max-w-7xl flex-wrap items-center justify-between gap-4 px-4 py-4 sm:px-6">
          <div className="flex items-center gap-3">
            <Link
              href="/inventory"
              className="rounded-lg border border-slate-800 p-2 text-slate-400 hover:bg-slate-800 hover:text-white transition"
              title="Back to Inventory Dashboard"
            >
              <ArrowLeft size={18} />
            </Link>
            <div className="rounded-xl bg-blue-600/20 border border-blue-500/30 p-2.5 text-blue-400">
              <Package size={22} />
            </div>
            <div>
              <h1 className="text-xl font-bold tracking-tight text-white sm:text-2xl">
                Products &amp; Materials
              </h1>
              <p className="text-xs text-slate-400">
                Simple catalog with custom categories, units, and inventory tracking
              </p>
            </div>
          </div>

          {/* Action Buttons */}
          <div className="flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={handleOpenAddProduct}
              className="inline-flex items-center gap-1.5 rounded-lg bg-blue-600 px-3.5 py-2 text-xs font-semibold text-white hover:bg-blue-500 transition shadow-sm shadow-blue-900/30"
            >
              <Plus size={15} /> Add Product / Material
            </button>

            <button
              type="button"
              onClick={() => handleOpenStockModal("IN")}
              className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800/80 px-3 py-2 text-xs font-medium text-emerald-400 hover:bg-slate-800 hover:text-emerald-300 transition"
              title="Record incoming stock"
            >
              <ArrowDownLeft size={14} /> Stock In
            </button>

            <button
              type="button"
              onClick={() => handleOpenStockModal("OUT")}
              className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-800/80 px-3 py-2 text-xs font-medium text-amber-400 hover:bg-slate-800 hover:text-amber-300 transition"
              title="Record stock dispatch"
            >
              <ArrowUpRight size={14} /> Stock Out
            </button>

            <div className="flex items-center gap-1 border-l border-slate-800 pl-2">
              <button
                type="button"
                onClick={() => setShowCategoryModal(true)}
                className="rounded-lg border border-slate-800 bg-slate-900/80 px-2.5 py-2 text-xs font-medium text-slate-300 hover:bg-slate-800 hover:text-white transition"
                title="Manage Custom Categories"
              >
                <Tag size={13} className="inline mr-1 text-blue-400" /> Categories
              </button>
              <button
                type="button"
                onClick={() => setShowUnitModal(true)}
                className="rounded-lg border border-slate-800 bg-slate-900/80 px-2.5 py-2 text-xs font-medium text-slate-300 hover:bg-slate-800 hover:text-white transition"
                title="Manage Custom Units"
              >
                <Ruler size={13} className="inline mr-1 text-emerald-400" /> Units
              </button>
            </div>
          </div>
        </div>
      </header>

      {/* Main Container */}
      <div className="mx-auto max-w-7xl px-4 py-6 sm:px-6 space-y-5">
        {/* Alerts / Notice banner */}
        {notice && (
          <div
            className={`flex items-center justify-between gap-3 rounded-xl p-3.5 text-xs font-medium border ${
              notice.type === "success"
                ? "bg-emerald-950/40 border-emerald-500/30 text-emerald-300"
                : "bg-rose-950/40 border-rose-500/30 text-rose-300"
            }`}
          >
            <div className="flex items-center gap-2">
              {notice.type === "success" ? (
                <CheckCircle2 size={16} className="text-emerald-400 shrink-0" />
              ) : (
                <AlertTriangle size={16} className="text-rose-400 shrink-0" />
              )}
              <span>{notice.text}</span>
            </div>
            <button
              type="button"
              onClick={() => setNotice(null)}
              className="text-slate-400 hover:text-white"
            >
              <X size={15} />
            </button>
          </div>
        )}

        {/* Filter Bar */}
        <div className="flex flex-col gap-3 rounded-xl border border-slate-800 bg-slate-950/60 p-4 sm:flex-row sm:items-center sm:justify-between">
          <div className="relative flex-1 max-w-md">
            <Search className="absolute left-3 top-2.5 text-slate-500" size={15} />
            <input
              type="text"
              placeholder="Search by name, SKU, category, supplier..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full rounded-lg border border-slate-800 bg-slate-900 pl-9 pr-4 py-2 text-xs text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none focus:ring-1 focus:ring-blue-500"
            />
          </div>

          <div className="flex flex-wrap items-center gap-2 text-xs">
            {/* Product Type Filter */}
            <select
              value={typeFilter}
              onChange={(e) => setTypeFilter(e.target.value as "all" | ProductType)}
              className="rounded-lg border border-slate-800 bg-slate-900 px-3 py-2 text-slate-300 focus:border-blue-500 focus:outline-none"
            >
              <option value="all">All Product Types</option>
              <option value="material">Materials</option>
              <option value="finished_product">Finished Products</option>
              <option value="service">Services (No Stock)</option>
            </select>

            {/* Category Filter */}
            <select
              value={categoryFilter}
              onChange={(e) => setCategoryFilter(e.target.value)}
              className="rounded-lg border border-slate-800 bg-slate-900 px-3 py-2 text-slate-300 focus:border-blue-500 focus:outline-none"
            >
              <option value="all">All Categories</option>
              {settings.categories.map((c) => (
                <option key={c.id} value={c.name}>
                  {c.name}
                </option>
              ))}
            </select>

            {/* Status Filter Pills */}
            <div className="flex items-center rounded-lg border border-slate-800 bg-slate-900 p-0.5">
              <button
                type="button"
                onClick={() => setStatusFilter("active")}
                className={`rounded-md px-2.5 py-1 text-xs font-medium transition ${
                  statusFilter === "active"
                    ? "bg-slate-800 text-white font-semibold shadow-xs"
                    : "text-slate-400 hover:text-white"
                }`}
              >
                Active ({counts.active})
              </button>
              <button
                type="button"
                onClick={() => setStatusFilter("inactive")}
                className={`rounded-md px-2.5 py-1 text-xs font-medium transition ${
                  statusFilter === "inactive"
                    ? "bg-slate-800 text-white font-semibold shadow-xs"
                    : "text-slate-400 hover:text-white"
                }`}
              >
                Inactive ({counts.inactive})
              </button>
              <button
                type="button"
                onClick={() => setStatusFilter("all")}
                className={`rounded-md px-2.5 py-1 text-xs font-medium transition ${
                  statusFilter === "all"
                    ? "bg-slate-800 text-white font-semibold shadow-xs"
                    : "text-slate-400 hover:text-white"
                }`}
              >
                All ({counts.total})
              </button>
            </div>
          </div>
        </div>

        {/* Product Table Card */}
        <div className="overflow-hidden rounded-xl border border-slate-800 bg-slate-950/60 shadow-md">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs text-slate-300">
              <thead className="border-b border-slate-800 bg-slate-900/90 uppercase font-semibold text-slate-400 tracking-wider">
                <tr>
                  <th className="px-4 py-3.5">Product / Material</th>
                  <th className="px-4 py-3.5">Category</th>
                  <th className="px-4 py-3.5">Unit</th>
                  <th className="px-4 py-3.5 text-right">Selling Price</th>
                  <th className="px-4 py-3.5 text-right">Available Stock</th>
                  <th className="px-4 py-3.5 text-center">Status</th>
                  <th className="px-4 py-3.5 text-right w-44">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/80">
                {loading ? (
                  <tr>
                    <td colSpan={7} className="px-4 py-16 text-center text-slate-500">
                      <Loader2 size={24} className="mx-auto animate-spin mb-2 text-blue-500" />
                      Loading products &amp; materials...
                    </td>
                  </tr>
                ) : filteredProducts.length === 0 ? (
                  <tr>
                    <td colSpan={7} className="px-4 py-16 text-center text-slate-500 space-y-2">
                      <Package size={32} className="mx-auto text-slate-600 mb-1" />
                      <p className="text-sm font-semibold text-slate-400">No products found</p>
                      <p className="text-xs text-slate-500 max-w-sm mx-auto">
                        {search || categoryFilter !== "all" || typeFilter !== "all"
                          ? "Try clearing filters to find what you are looking for."
                          : "Get started by adding your first product, raw material, or service."}
                      </p>
                      <button
                        type="button"
                        onClick={handleOpenAddProduct}
                        className="mt-2 inline-flex items-center gap-1.5 rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white hover:bg-blue-500 transition"
                      >
                        <Plus size={14} /> Add Product Now
                      </button>
                    </td>
                  </tr>
                ) : (
                  filteredProducts.map((p) => {
                    const matchedCategory = settings.categories.find(
                      (c) => c.name.toLowerCase() === p.category.toLowerCase()
                    );
                    const catColor = matchedCategory?.color || "#64748B";

                    return (
                      <tr
                        key={p.id}
                        className="hover:bg-slate-900/60 transition-colors group"
                      >
                        {/* Name & SKU */}
                        <td className="px-4 py-3.5">
                          <div className="flex flex-col">
                            <span className="font-semibold text-white group-hover:text-blue-400 transition-colors">
                              {p.name}
                            </span>
                            <div className="flex items-center gap-2 mt-0.5">
                              {p.sku ? (
                                <span className="font-mono text-[11px] text-slate-400">
                                  SKU: {p.sku}
                                </span>
                              ) : null}
                              <span
                                className={`text-[10px] px-1.5 py-0.2 rounded font-medium ${
                                  p.product_type === "service"
                                    ? "bg-purple-950 text-purple-300 border border-purple-800"
                                    : p.product_type === "finished_product"
                                    ? "bg-emerald-950 text-emerald-300 border border-emerald-800"
                                    : "bg-blue-950 text-blue-300 border border-blue-800"
                                }`}
                              >
                                {p.product_type === "service"
                                  ? "Service"
                                  : p.product_type === "finished_product"
                                  ? "Finished Product"
                                  : "Material"}
                              </span>
                            </div>
                          </div>
                        </td>

                        {/* Category */}
                        <td className="px-4 py-3.5 whitespace-nowrap">
                          <span
                            className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-medium border"
                            style={{
                              backgroundColor: `${catColor}15`,
                              borderColor: `${catColor}40`,
                              color: catColor,
                            }}
                          >
                            <span
                              className="w-1.5 h-1.5 rounded-full"
                              style={{ backgroundColor: catColor }}
                            />
                            {p.category}
                          </span>
                        </td>

                        {/* Unit */}
                        <td className="px-4 py-3.5 font-mono text-slate-300 whitespace-nowrap">
                          {p.unit}
                        </td>

                        {/* Selling Price */}
                        <td className="px-4 py-3.5 text-right font-mono text-white whitespace-nowrap">
                          {p.selling_price > 0 ? fmtAED(p.selling_price) : "—"}
                        </td>

                        {/* Available Stock */}
                        <td className="px-4 py-3.5 text-right whitespace-nowrap">
                          {p.is_service ? (
                            <span className="inline-flex items-center gap-1 rounded bg-slate-800 px-2 py-0.5 text-[11px] text-slate-400">
                              Service / No Stock
                            </span>
                          ) : (
                            <div>
                              <span
                                className={`font-mono font-bold ${
                                  p.current_stock <= 0
                                    ? "text-rose-400"
                                    : p.minimum_stock > 0 && p.current_stock <= p.minimum_stock
                                    ? "text-amber-400"
                                    : "text-emerald-400"
                                }`}
                              >
                                {p.current_stock.toLocaleString("en-US", { maximumFractionDigits: 3 })}
                              </span>{" "}
                              <span className="text-[11px] text-slate-400 font-sans">{p.unit}</span>
                              {p.minimum_stock > 0 && p.current_stock <= p.minimum_stock && (
                                <span className="block text-[10px] text-amber-400">Low Stock Alert</span>
                              )}
                            </div>
                          )}
                        </td>

                        {/* Active / Inactive */}
                        <td className="px-4 py-3.5 text-center whitespace-nowrap">
                          <span
                            className={`inline-block px-2 py-0.5 rounded text-[11px] font-medium ${
                              p.active
                                ? "bg-emerald-950/60 text-emerald-400 border border-emerald-800/40"
                                : "bg-slate-800 text-slate-500 border border-slate-700"
                            }`}
                          >
                            {p.active ? "Active" : "Inactive"}
                          </span>
                        </td>

                        {/* Actions */}
                        <td className="px-4 py-3.5 text-right whitespace-nowrap">
                          <div className="flex items-center justify-end gap-1.5">
                            {!p.is_service && (
                              <>
                                <button
                                  type="button"
                                  onClick={() => handleOpenStockModal("IN", p)}
                                  className="rounded p-1.5 text-slate-400 hover:bg-slate-800 hover:text-emerald-400 transition"
                                  title="Quick Stock In"
                                >
                                  <ArrowDownLeft size={14} />
                                </button>
                                <button
                                  type="button"
                                  onClick={() => handleOpenStockModal("OUT", p)}
                                  className="rounded p-1.5 text-slate-400 hover:bg-slate-800 hover:text-amber-400 transition"
                                  title="Quick Stock Out"
                                >
                                  <ArrowUpRight size={14} />
                                </button>
                                <button
                                  type="button"
                                  onClick={() => handleOpenHistory(p)}
                                  className="rounded p-1.5 text-slate-400 hover:bg-slate-800 hover:text-blue-400 transition"
                                  title="Movement History"
                                >
                                  <History size={14} />
                                </button>
                              </>
                            )}

                            <button
                              type="button"
                              onClick={() => handleOpenEditProduct(p)}
                              className="rounded p-1.5 text-slate-400 hover:bg-slate-800 hover:text-white transition"
                              title="Edit Product"
                            >
                              <Pencil size={14} />
                            </button>

                            <button
                              type="button"
                              onClick={() => handleToggleStatus(p)}
                              disabled={togglingId === p.id}
                              className={`rounded p-1.5 transition ${
                                p.active
                                  ? "text-slate-400 hover:bg-rose-950/40 hover:text-rose-400"
                                  : "text-slate-600 hover:bg-emerald-950/40 hover:text-emerald-400"
                              }`}
                              title={p.active ? "Deactivate Product" : "Activate Product"}
                            >
                              {togglingId === p.id ? (
                                <Loader2 size={14} className="animate-spin text-slate-400" />
                              ) : (
                                <Power size={14} />
                              )}
                            </button>
                          </div>
                        </td>
                      </tr>
                    );
                  })
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>

      {/* ============================================================ */}
      {/* 1. SIMPLE PRODUCT CREATION & EDIT MODAL                      */}
      {/* ============================================================ */}
      {showProductModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-950/80 backdrop-blur-sm overflow-y-auto">
          <div className="relative w-full max-w-2xl rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden my-6">
            {/* Modal Header */}
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2.5">
                <div className="rounded-xl bg-blue-600/20 p-2 text-blue-400">
                  <Package size={20} />
                </div>
                <div>
                  <h2 className="text-base font-bold text-white">
                    {draft.id ? "Edit Product / Material" : "Add Product / Material"}
                  </h2>
                  <p className="text-xs text-slate-400">
                    Fill the four core fields, or expand More Options for detailed inventory settings
                  </p>
                </div>
              </div>
              <button
                type="button"
                onClick={() => setShowProductModal(false)}
                className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-800 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            {/* Modal Body */}
            <form onSubmit={handleSaveProduct} className="p-6 space-y-5">
              {/* Product Type Selector */}
              <div>
                <label className="mb-1.5 block text-xs font-semibold text-slate-300">
                  Product Type
                </label>
                <div className="grid grid-cols-3 gap-2">
                  <button
                    type="button"
                    onClick={() => {
                      setDraft((p) => ({ ...p, product_type: "material" }));
                      if (!draft.sku || skuAutoGenerated) {
                        setDraft((p) => ({
                          ...p,
                          sku: generateSuggestedSku(p.name, "material"),
                        }));
                        setSkuAutoGenerated(true);
                      }
                    }}
                    className={`flex items-center justify-center gap-1.5 rounded-lg border p-2.5 text-xs font-semibold transition ${
                      draft.product_type === "material"
                        ? "border-blue-500 bg-blue-600/20 text-white shadow-xs"
                        : "border-slate-800 bg-slate-950 text-slate-400 hover:text-white"
                    }`}
                  >
                    <Package size={14} className="text-blue-400" />
                    Material
                  </button>

                  <button
                    type="button"
                    onClick={() => {
                      setDraft((p) => ({ ...p, product_type: "finished_product" }));
                      if (!draft.sku || skuAutoGenerated) {
                        setDraft((p) => ({
                          ...p,
                          sku: generateSuggestedSku(p.name, "finished_product"),
                        }));
                        setSkuAutoGenerated(true);
                      }
                    }}
                    className={`flex items-center justify-center gap-1.5 rounded-lg border p-2.5 text-xs font-semibold transition ${
                      draft.product_type === "finished_product"
                        ? "border-emerald-500 bg-emerald-600/20 text-white shadow-xs"
                        : "border-slate-800 bg-slate-950 text-slate-400 hover:text-white"
                    }`}
                  >
                    <Boxes size={14} className="text-emerald-400" />
                    Finished Product
                  </button>

                  <button
                    type="button"
                    onClick={() => {
                      setDraft((p) => ({ ...p, product_type: "service" }));
                      if (!draft.sku || skuAutoGenerated) {
                        setDraft((p) => ({
                          ...p,
                          sku: generateSuggestedSku(p.name, "service"),
                        }));
                        setSkuAutoGenerated(true);
                      }
                    }}
                    className={`flex items-center justify-center gap-1.5 rounded-lg border p-2.5 text-xs font-semibold transition ${
                      draft.product_type === "service"
                        ? "border-purple-500 bg-purple-600/20 text-white shadow-xs"
                        : "border-slate-800 bg-slate-950 text-slate-400 hover:text-white"
                    }`}
                  >
                    <Briefcase size={14} className="text-purple-400" />
                    Service (No Stock)
                  </button>
                </div>
              </div>

              {/* CORE 4 FIELDS */}
              <div className="rounded-xl border border-slate-800 bg-slate-950/60 p-4 space-y-4">
                <span className="text-[11px] font-bold uppercase tracking-wider text-slate-400 block">
                  Core Details
                </span>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 text-xs">
                  {/* Field 1: Name */}
                  <div className="sm:col-span-2">
                    <label className="mb-1 block font-semibold text-slate-200">
                      Product / Material Name <span className="text-rose-400">*</span>
                    </label>
                    <input
                      type="text"
                      required
                      placeholder="e.g. PVC Fabric 650 GSM White, Welding Labor, or Water Tank Liner 2000L"
                      value={draft.name}
                      onChange={(e) => {
                        const nextName = e.target.value;
                        setDraft((prev) => {
                          const updated = { ...prev, name: nextName };
                          if (!prev.sku || skuAutoGenerated) {
                            updated.sku = generateSuggestedSku(nextName, prev.product_type);
                            setSkuAutoGenerated(true);
                          }
                          return updated;
                        });
                      }}
                      className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                    />
                  </div>

                  {/* Field 2: Category */}
                  <div>
                    <div className="flex items-center justify-between mb-1">
                      <label className="font-semibold text-slate-200">Category</label>
                      <button
                        type="button"
                        onClick={() => setShowCategoryModal(true)}
                        className="text-[11px] text-blue-400 hover:underline inline-flex items-center gap-0.5"
                      >
                        <Plus size={12} /> Custom Category
                      </button>
                    </div>
                    <select
                      value={draft.category}
                      onChange={(e) => setDraft((p) => ({ ...p, category: e.target.value }))}
                      className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white focus:border-blue-500 focus:outline-none"
                    >
                      {settings.categories
                        .filter((c) => c.active || c.name === draft.category)
                        .map((c) => (
                          <option key={c.id} value={c.name}>
                            {c.name}
                          </option>
                        ))}
                    </select>
                  </div>

                  {/* Field 3: Unit */}
                  <div>
                    <div className="flex items-center justify-between mb-1">
                      <label className="font-semibold text-slate-200">Unit of Measurement</label>
                      <button
                        type="button"
                        onClick={() => setShowUnitModal(true)}
                        className="text-[11px] text-emerald-400 hover:underline inline-flex items-center gap-0.5"
                      >
                        <Plus size={12} /> Custom Unit
                      </button>
                    </div>
                    <select
                      value={draft.unit}
                      onChange={(e) => setDraft((p) => ({ ...p, unit: e.target.value }))}
                      className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white focus:border-blue-500 focus:outline-none"
                    >
                      {settings.units
                        .filter((u) => u.active || u.code === draft.unit)
                        .map((u) => (
                          <option key={u.code} value={u.code}>
                            {u.code} — {u.name}
                          </option>
                        ))}
                    </select>
                  </div>

                  {/* Field 4: Selling Price */}
                  <div>
                    <label className="mb-1 block font-semibold text-slate-200">
                      Selling Price (AED) <span className="text-slate-500 font-normal">(Optional)</span>
                    </label>
                    <input
                      type="number"
                      step="0.01"
                      min="0"
                      placeholder="0.00"
                      value={draft.selling_price}
                      onChange={(e) => setDraft((p) => ({ ...p, selling_price: e.target.value }))}
                      className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                    />
                  </div>
                </div>
              </div>

              {/* MORE OPTIONS ACCORDION */}
              <div className="rounded-xl border border-slate-800 bg-slate-950/40 overflow-hidden">
                <button
                  type="button"
                  onClick={() => setShowMoreOptions(!showMoreOptions)}
                  className="w-full flex items-center justify-between px-4 py-3 text-xs font-semibold text-slate-300 hover:text-white hover:bg-slate-800/40 transition"
                >
                  <span className="flex items-center gap-2">
                    <Settings2 size={14} className="text-blue-400" />
                    More Options (SKU, Purchase Price, VAT, Opening Stock, Notes &amp; Custom Fields)
                  </span>
                  {showMoreOptions ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
                </button>

                {showMoreOptions && (
                  <div className="p-4 pt-2 border-t border-slate-800 space-y-4 text-xs">
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                      {/* SKU */}
                      <div>
                        <div className="flex items-center justify-between mb-1">
                          <label className="font-semibold text-slate-300">SKU / Item Code</label>
                          <button
                            type="button"
                            onClick={() => {
                              const s = generateSuggestedSku(draft.name, draft.product_type);
                              setDraft((p) => ({ ...p, sku: s }));
                              setSkuAutoGenerated(false);
                            }}
                            className="text-[11px] text-blue-400 hover:underline"
                          >
                            Suggest SKU
                          </button>
                        </div>
                        <input
                          type="text"
                          placeholder="e.g. PVC-650-WHT"
                          value={draft.sku}
                          onChange={(e) => {
                            setDraft((p) => ({ ...p, sku: e.target.value }));
                            setSkuAutoGenerated(false);
                          }}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                        />
                      </div>

                      {/* Cost / Purchase Price */}
                      <div>
                        <label className="mb-1 block font-semibold text-slate-300">
                          Purchase / Cost Price (AED)
                        </label>
                        <input
                          type="number"
                          step="0.01"
                          min="0"
                          placeholder="0.00"
                          value={draft.cost_price}
                          onChange={(e) => setDraft((p) => ({ ...p, cost_price: e.target.value }))}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                        />
                      </div>

                      {/* VAT Percentage */}
                      <div>
                        <label className="mb-1 block font-semibold text-slate-300">
                          VAT Rate (%)
                        </label>
                        <select
                          value={draft.vat_rate}
                          onChange={(e) => setDraft((p) => ({ ...p, vat_rate: e.target.value }))}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white focus:border-blue-500 focus:outline-none"
                        >
                          <option value="5">5% Standard UAE VAT</option>
                          <option value="0">0% Zero-Rated</option>
                        </select>
                      </div>

                      {/* Supplier */}
                      <div>
                        <label className="mb-1 block font-semibold text-slate-300">
                          Supplier / Vendor
                        </label>
                        <input
                          type="text"
                          placeholder="e.g. Al Safwah Fabrics / Korean Textiles"
                          value={draft.supplier_name}
                          onChange={(e) => setDraft((p) => ({ ...p, supplier_name: e.target.value }))}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                        />
                      </div>

                      {/* Opening Stock & Min Stock (Only for physical goods) */}
                      {draft.product_type !== "service" && (
                        <>
                          <div>
                            <label className="mb-1 block font-semibold text-slate-300">
                              Opening Stock ({draft.unit})
                            </label>
                            <input
                              type="number"
                              step="0.01"
                              min="0"
                              disabled={Boolean(draft.id)}
                              placeholder="0.00"
                              value={draft.opening_stock}
                              onChange={(e) => setDraft((p) => ({ ...p, opening_stock: e.target.value }))}
                              className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none disabled:opacity-50"
                            />
                            {draft.id ? (
                              <span className="text-[10px] text-slate-500 mt-0.5 block">
                                To adjust existing stock, use Stock In / Stock Out
                              </span>
                            ) : (
                              <span className="text-[10px] text-slate-400 mt-0.5 block">
                                Creates an audited opening stock movement
                              </span>
                            )}
                          </div>

                          <div>
                            <label className="mb-1 block font-semibold text-slate-300">
                              Minimum Stock Alert ({draft.unit})
                            </label>
                            <input
                              type="number"
                              step="0.01"
                              min="0"
                              placeholder="0"
                              value={draft.minimum_stock}
                              onChange={(e) => setDraft((p) => ({ ...p, minimum_stock: e.target.value }))}
                              className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                            />
                          </div>
                        </>
                      )}

                      {/* Description */}
                      <div className="sm:col-span-2">
                        <label className="mb-1 block font-semibold text-slate-300">
                          Description (Customer Facing)
                        </label>
                        <textarea
                          rows={2}
                          placeholder="Detailed product specifications to display on invoices and quotations..."
                          value={draft.description}
                          onChange={(e) => setDraft((p) => ({ ...p, description: e.target.value }))}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                        />
                      </div>

                      {/* Internal Notes */}
                      <div className="sm:col-span-2">
                        <label className="mb-1 block font-semibold text-slate-300">
                          Internal Notes
                        </label>
                        <input
                          type="text"
                          placeholder="e.g. Storage bay 3, reorder lead time 2 weeks..."
                          value={draft.notes}
                          onChange={(e) => setDraft((p) => ({ ...p, notes: e.target.value }))}
                          className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs text-white placeholder-slate-500 focus:border-blue-500 focus:outline-none"
                        />
                      </div>
                    </div>

                    {/* DYNAMIC CUSTOM FIELDS SECTION */}
                    <div className="border-t border-slate-800 pt-3">
                      <div className="flex items-center justify-between mb-3">
                        <span className="font-bold text-slate-300 flex items-center gap-1.5">
                          <Tag size={13} className="text-blue-400" /> Custom Fields
                        </span>
                        <button
                          type="button"
                          onClick={() => setShowCustomFieldModal(true)}
                          className="inline-flex items-center gap-1 text-[11px] text-blue-400 hover:underline"
                        >
                          <Plus size={12} /> Add Custom Field
                        </button>
                      </div>

                      {settings.custom_fields.length === 0 ? (
                        <p className="text-[11px] text-slate-500 bg-slate-950 p-2.5 rounded-lg border border-slate-800/80">
                          No custom fields defined yet. Click &quot;Add Custom Field&quot; to add custom attributes like Fabric Width, GSM, Color, Roll Length, or Batch Number.
                        </p>
                      ) : (
                        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 bg-slate-950 p-3 rounded-lg border border-slate-800">
                          {settings.custom_fields
                            .filter((f) => f.active)
                            .map((field) => (
                              <div key={field.id}>
                                <label className="mb-1 block font-medium text-slate-300">
                                  {field.name} {field.required && <span className="text-rose-400">*</span>}
                                </label>
                                {field.type === "dropdown" ? (
                                  <select
                                    value={String(draft.custom_field_values[field.key] ?? field.default_value ?? "")}
                                    onChange={(e) =>
                                      setDraft((prev) => ({
                                        ...prev,
                                        custom_field_values: {
                                          ...prev.custom_field_values,
                                          [field.key]: e.target.value,
                                        },
                                      }))
                                    }
                                    className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-1.5 text-xs text-white focus:border-blue-500 focus:outline-none"
                                  >
                                    <option value="">Select {field.name}...</option>
                                    {(field.options || []).map((opt) => (
                                      <option key={opt} value={opt}>
                                        {opt}
                                      </option>
                                    ))}
                                  </select>
                                ) : field.type === "boolean" ? (
                                  <select
                                    value={String(draft.custom_field_values[field.key] ?? field.default_value ?? "No")}
                                    onChange={(e) =>
                                      setDraft((prev) => ({
                                        ...prev,
                                        custom_field_values: {
                                          ...prev.custom_field_values,
                                          [field.key]: e.target.value === "Yes",
                                        },
                                      }))
                                    }
                                    className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-1.5 text-xs text-white focus:border-blue-500 focus:outline-none"
                                  >
                                    <option value="Yes">Yes</option>
                                    <option value="No">No</option>
                                  </select>
                                ) : (
                                  <input
                                    type={field.type === "number" || field.type === "decimal" ? "number" : field.type === "date" ? "date" : "text"}
                                    step={field.type === "decimal" ? "0.01" : undefined}
                                    placeholder={field.default_value || `Enter ${field.name.toLowerCase()}...`}
                                    value={String(draft.custom_field_values[field.key] ?? "")}
                                    onChange={(e) =>
                                      setDraft((prev) => ({
                                        ...prev,
                                        custom_field_values: {
                                          ...prev.custom_field_values,
                                          [field.key]: e.target.value,
                                        },
                                      }))
                                    }
                                    className="w-full rounded-lg border border-slate-700 bg-slate-900 px-3 py-1.5 text-xs text-white focus:border-blue-500 focus:outline-none"
                                  />
                                )}
                              </div>
                            ))}
                        </div>
                      )}
                    </div>
                  </div>
                )}
              </div>

              {/* Modal Footer */}
              <div className="flex items-center justify-end gap-3 pt-3 border-t border-slate-800">
                <button
                  type="button"
                  onClick={() => setShowProductModal(false)}
                  className="rounded-lg border border-slate-700 bg-slate-800 px-4 py-2 text-xs font-semibold text-slate-300 hover:bg-slate-700 hover:text-white transition"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={saving}
                  className="inline-flex items-center gap-1.5 rounded-lg bg-blue-600 px-5 py-2 text-xs font-semibold text-white hover:bg-blue-500 transition shadow-sm disabled:opacity-50"
                >
                  {saving ? (
                    <>
                      <Loader2 size={14} className="animate-spin" /> Saving...
                    </>
                  ) : (
                    "Save Product"
                  )}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ============================================================ */}
      {/* 2. CUSTOM CATEGORY MANAGEMENT MODAL                         */}
      {/* ============================================================ */}
      {showCategoryModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-lg rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2">
                <Tag size={18} className="text-blue-400" />
                <h3 className="text-base font-bold text-white">Custom Categories</h3>
              </div>
              <button
                type="button"
                onClick={() => setShowCategoryModal(false)}
                className="text-slate-400 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            <div className="p-6 space-y-4 text-xs">
              {/* Add Category Form */}
              <form onSubmit={handleAddCategory} className="flex gap-2">
                <input
                  type="text"
                  required
                  placeholder="New category name (e.g. Tarpaulin Covers, Shade Netting)"
                  value={newCatName}
                  onChange={(e) => setNewCatName(e.target.value)}
                  className="flex-1 rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-xs text-white focus:border-blue-500 focus:outline-none"
                />
                <input
                  type="color"
                  value={newCatColor}
                  onChange={(e) => setNewCatColor(e.target.value)}
                  className="w-10 h-9 p-1 rounded-lg border border-slate-700 bg-slate-950 cursor-pointer"
                  title="Category Badge Color"
                />
                <button
                  type="submit"
                  className="rounded-lg bg-blue-600 px-3.5 py-2 font-semibold text-white hover:bg-blue-500 transition"
                >
                  Add
                </button>
              </form>

              {/* Categories List */}
              <div className="max-h-60 overflow-y-auto divide-y divide-slate-800 border border-slate-800 rounded-xl bg-slate-950/50">
                {settings.categories.map((cat) => {
                  const usage = materials.filter(
                    (m) => m.category.toLowerCase().trim() === cat.name.toLowerCase().trim()
                  ).length;

                  return (
                    <div
                      key={cat.id}
                      className="flex items-center justify-between p-3 hover:bg-slate-900/60 transition"
                    >
                      <div className="flex items-center gap-2">
                        <span
                          className="w-3 h-3 rounded-full shrink-0"
                          style={{ backgroundColor: cat.color || "#64748B" }}
                        />
                        <span className={`font-medium ${cat.active ? "text-white" : "text-slate-500 line-through"}`}>
                          {cat.name}
                        </span>
                        <span className="text-[10px] text-slate-500">
                          ({usage} product{usage === 1 ? "" : "s"})
                        </span>
                      </div>

                      <button
                        type="button"
                        onClick={() => handleToggleCategory(cat.id)}
                        className={`text-[11px] px-2.5 py-1 rounded transition ${
                          cat.active
                            ? "border border-slate-700 text-slate-400 hover:text-rose-400 hover:border-rose-900"
                            : "border border-emerald-800 text-emerald-400"
                        }`}
                      >
                        {cat.active ? "Deactivate" : "Activate"}
                      </button>
                    </div>
                  );
                })}
              </div>
            </div>

            <div className="flex justify-end p-4 border-t border-slate-800 bg-slate-950/40">
              <button
                type="button"
                onClick={() => setShowCategoryModal(false)}
                className="rounded-lg bg-slate-800 px-4 py-1.5 text-xs font-semibold text-white hover:bg-slate-700"
              >
                Done
              </button>
            </div>
          </div>
        </div>
      )}

      {/* ============================================================ */}
      {/* 3. CUSTOM UNIT MANAGEMENT MODAL                             */}
      {/* ============================================================ */}
      {showUnitModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-lg rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2">
                <Ruler size={18} className="text-emerald-400" />
                <h3 className="text-base font-bold text-white">Custom Units of Measurement</h3>
              </div>
              <button
                type="button"
                onClick={() => setShowUnitModal(false)}
                className="text-slate-400 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            <div className="p-6 space-y-4 text-xs">
              {/* Add Unit Form */}
              <form onSubmit={handleAddUnit} className="grid grid-cols-5 gap-2">
                <input
                  type="text"
                  required
                  placeholder="Code (e.g. BOX)"
                  value={newUnitCode}
                  onChange={(e) => setNewUnitCode(e.target.value.toUpperCase())}
                  className="col-span-2 rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-xs font-mono text-white focus:border-emerald-500 focus:outline-none"
                />
                <input
                  type="text"
                  placeholder="Display Name (e.g. Boxes)"
                  value={newUnitName}
                  onChange={(e) => setNewUnitName(e.target.value)}
                  className="col-span-2 rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-xs text-white focus:border-emerald-500 focus:outline-none"
                />
                <button
                  type="submit"
                  className="rounded-lg bg-emerald-600 px-3 py-2 font-semibold text-white hover:bg-emerald-500 transition"
                >
                  Add
                </button>
              </form>

              {/* Units List */}
              <div className="max-h-60 overflow-y-auto divide-y divide-slate-800 border border-slate-800 rounded-xl bg-slate-950/50">
                {settings.units.map((u) => {
                  const usage = materials.filter(
                    (m) => m.unit.toUpperCase() === u.code.toUpperCase()
                  ).length;

                  return (
                    <div
                      key={u.code}
                      className="flex items-center justify-between p-3 hover:bg-slate-900/60 transition"
                    >
                      <div>
                        <span className="font-mono font-bold text-white mr-2">{u.code}</span>
                        <span className={`text-slate-400 ${u.active ? "" : "line-through text-slate-500"}`}>
                          ({u.name})
                        </span>
                        <span className="text-[10px] text-slate-500 ml-2">
                          ({usage} product{usage === 1 ? "" : "s"})
                        </span>
                      </div>

                      <button
                        type="button"
                        onClick={() => handleToggleUnit(u.code)}
                        className={`text-[11px] px-2.5 py-1 rounded transition ${
                          u.active
                            ? "border border-slate-700 text-slate-400 hover:text-rose-400 hover:border-rose-900"
                            : "border border-emerald-800 text-emerald-400"
                        }`}
                      >
                        {u.active ? "Deactivate" : "Activate"}
                      </button>
                    </div>
                  );
                })}
              </div>
            </div>

            <div className="flex justify-end p-4 border-t border-slate-800 bg-slate-950/40">
              <button
                type="button"
                onClick={() => setShowUnitModal(false)}
                className="rounded-lg bg-slate-800 px-4 py-1.5 text-xs font-semibold text-white hover:bg-slate-700"
              >
                Done
              </button>
            </div>
          </div>
        </div>
      )}

      {/* ============================================================ */}
      {/* 4. CUSTOM FIELD BUILDER MODAL                                */}
      {/* ============================================================ */}
      {showCustomFieldModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-md rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2">
                <Tag size={18} className="text-blue-400" />
                <h3 className="text-base font-bold text-white">Add Custom Product Field</h3>
              </div>
              <button
                type="button"
                onClick={() => setShowCustomFieldModal(false)}
                className="text-slate-400 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            <form onSubmit={handleAddCustomField} className="p-6 space-y-4 text-xs">
              <div>
                <label className="mb-1 block font-semibold text-slate-200">
                  Field Label <span className="text-rose-400">*</span>
                </label>
                <input
                  type="text"
                  required
                  placeholder="e.g. Fabric Width, GSM, Roll Length, Storage Bay"
                  value={newFieldName}
                  onChange={(e) => setNewFieldName(e.target.value)}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                />
              </div>

              <div>
                <label className="mb-1 block font-semibold text-slate-200">Field Type</label>
                <select
                  value={newFieldType}
                  onChange={(e) => setNewFieldType(e.target.value as CustomFieldType)}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                >
                  <option value="text">Text (e.g. Color, Manufacturer)</option>
                  <option value="number">Whole Number (e.g. GSM, Quantity)</option>
                  <option value="decimal">Decimal (e.g. 2.50 Metres, 0.85mm)</option>
                  <option value="dropdown">Dropdown (Select list)</option>
                  <option value="boolean">Yes / No Toggle</option>
                  <option value="date">Date</option>
                </select>
              </div>

              {newFieldType === "dropdown" && (
                <div>
                  <label className="mb-1 block font-semibold text-slate-200">
                    Dropdown Options (Comma-separated)
                  </label>
                  <input
                    type="text"
                    required
                    placeholder="e.g. White, Blue, Beige, Black"
                    value={newFieldOptions}
                    onChange={(e) => setNewFieldOptions(e.target.value)}
                    className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                  />
                </div>
              )}

              <div>
                <label className="mb-1 block font-semibold text-slate-200">
                  Default Value <span className="text-slate-500 font-normal">(Optional)</span>
                </label>
                <input
                  type="text"
                  placeholder="e.g. 3.00, White, None"
                  value={newFieldDefault}
                  onChange={(e) => setNewFieldDefault(e.target.value)}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                />
              </div>

              <div className="flex items-center gap-2 pt-1">
                <input
                  type="checkbox"
                  id="newFieldReq"
                  checked={newFieldRequired}
                  onChange={(e) => setNewFieldRequired(e.target.checked)}
                  className="rounded border-slate-700 bg-slate-950 text-blue-600 focus:ring-0"
                />
                <label htmlFor="newFieldReq" className="text-slate-300 font-medium cursor-pointer">
                  Require this field when adding products
                </label>
              </div>

              <div className="flex justify-end gap-2 pt-3 border-t border-slate-800">
                <button
                  type="button"
                  onClick={() => setShowCustomFieldModal(false)}
                  className="rounded-lg border border-slate-700 bg-slate-800 px-4 py-2 font-semibold text-slate-300 hover:bg-slate-700"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="rounded-lg bg-blue-600 px-4 py-2 font-semibold text-white hover:bg-blue-500"
                >
                  Create Field
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ============================================================ */}
      {/* 5. MOVEMENT HISTORY MODAL                                    */}
      {/* ============================================================ */}
      {showHistoryModal && historyProduct && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-3xl max-h-[85vh] flex flex-col rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2.5">
                <div className="rounded-xl bg-blue-600/20 p-2 text-blue-400">
                  <History size={18} />
                </div>
                <div>
                  <h3 className="text-base font-bold text-white">
                    Stock Movement History
                  </h3>
                  <p className="text-xs text-slate-400">
                    {historyProduct.name} {historyProduct.sku ? `(${historyProduct.sku})` : ""} &bull; Balance:{" "}
                    <strong className="text-emerald-400">
                      {historyProduct.current_stock} {historyProduct.unit}
                    </strong>
                  </p>
                </div>
              </div>
              <button
                type="button"
                onClick={() => setShowHistoryModal(false)}
                className="text-slate-400 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            <div className="p-6 overflow-y-auto space-y-4 text-xs">
              {historyLoading ? (
                <div className="py-12 text-center text-slate-500">
                  <Loader2 size={24} className="mx-auto animate-spin mb-2 text-blue-500" />
                  Loading audit log...
                </div>
              ) : historyMovements.length === 0 ? (
                <div className="p-8 text-center text-slate-500 bg-slate-950 rounded-xl border border-slate-800">
                  <History size={28} className="mx-auto text-slate-600 mb-2" />
                  <p className="font-semibold text-slate-400">No stock movements recorded yet.</p>
                  <p className="text-[11px] text-slate-500 mt-1">
                    Receipts, dispatches, and adjustments for this item will be audited here.
                  </p>
                </div>
              ) : (
                <div className="overflow-hidden rounded-xl border border-slate-800 bg-slate-950">
                  <table className="w-full text-left text-xs text-slate-300">
                    <thead className="bg-slate-900 text-slate-400 font-semibold border-b border-slate-800">
                      <tr>
                        <th className="px-3 py-2.5">Date</th>
                        <th className="px-3 py-2.5">Type</th>
                        <th className="px-3 py-2.5 text-right">Quantity</th>
                        <th className="px-3 py-2.5 text-right">Balance</th>
                        <th className="px-3 py-2.5">Reference #</th>
                        <th className="px-3 py-2.5">Purpose / Notes</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-slate-800/80 font-mono">
                      {historyMovements.map((m) => (
                        <tr key={m.id} className="hover:bg-slate-900/60">
                          <td className="px-3 py-2 text-slate-400 whitespace-nowrap font-sans">
                            {new Date(m.created_at).toLocaleDateString("en-AE", { dateStyle: "short" })}
                          </td>
                          <td className="px-3 py-2 font-sans">
                            <span
                              className={`px-1.5 py-0.5 rounded text-[10px] font-semibold ${
                                m.movement_type === "IN"
                                  ? "bg-emerald-950 text-emerald-400 border border-emerald-800"
                                  : m.movement_type === "OUT"
                                  ? "bg-amber-950 text-amber-400 border border-amber-800"
                                  : "bg-blue-950 text-blue-400 border border-blue-800"
                              }`}
                            >
                              {m.movement_type}
                            </span>
                          </td>
                          <td
                            className={`px-3 py-2 text-right font-bold ${
                              m.movement_type === "IN" ? "text-emerald-400" : "text-amber-400"
                            }`}
                          >
                            {m.movement_type === "IN" ? "+" : "-"}
                            {m.quantity.toLocaleString()}
                          </td>
                          <td className="px-3 py-2 text-right text-white">
                            {m.new_stock.toLocaleString()}
                          </td>
                          <td className="px-3 py-2 text-slate-300 font-sans">
                            {m.reference_number || "—"}
                          </td>
                          <td className="px-3 py-2 text-slate-400 font-sans truncate max-w-xs" title={m.notes || ""}>
                            {m.purpose || m.notes || "—"}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
            </div>

            <div className="flex justify-end p-4 border-t border-slate-800 bg-slate-950/40">
              <button
                type="button"
                onClick={() => setShowHistoryModal(false)}
                className="rounded-lg bg-slate-800 px-4 py-1.5 text-xs font-semibold text-white hover:bg-slate-700"
              >
                Close
              </button>
            </div>
          </div>
        </div>
      )}

      {/* ============================================================ */}
      {/* 6. QUICK STOCK ADJUSTMENT MODAL (IN / OUT)                   */}
      {/* ============================================================ */}
      {stockModalType && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-md rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950/60 px-6 py-4">
              <div className="flex items-center gap-2">
                {stockModalType === "IN" ? (
                  <ArrowDownLeft size={18} className="text-emerald-400" />
                ) : (
                  <ArrowUpRight size={18} className="text-amber-400" />
                )}
                <h3 className="text-base font-bold text-white">
                  {stockModalType === "IN" ? "Record Stock In" : "Record Stock Out"}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setStockModalType(null)}
                className="text-slate-400 hover:text-white"
              >
                <X size={18} />
              </button>
            </div>

            <form onSubmit={handleExecuteStockAdjustment} className="p-6 space-y-4 text-xs">
              <div>
                <label className="mb-1 block font-semibold text-slate-200">
                  Select Product / Material <span className="text-rose-400">*</span>
                </label>
                <select
                  required
                  value={stockModalProduct?.id || ""}
                  onChange={(e) => {
                    const sel = materials.find((m) => m.id === e.target.value);
                    if (sel) setStockModalProduct(sel);
                  }}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                >
                  {materials
                    .filter((m) => !m.is_service && m.active)
                    .map((m) => (
                      <option key={m.id} value={m.id}>
                        {m.name} ({m.current_stock} {m.unit} in stock)
                      </option>
                    ))}
                </select>
              </div>

              <div>
                <label className="mb-1 block font-semibold text-slate-200">
                  Quantity ({stockModalProduct?.unit || "Units"}) <span className="text-rose-400">*</span>
                </label>
                <input
                  type="number"
                  step="0.01"
                  min="0.01"
                  required
                  placeholder="0.00"
                  value={stockModalQty}
                  onChange={(e) => setStockModalQty(e.target.value)}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-white focus:border-blue-500 focus:outline-none"
                />
              </div>

              <div>
                <label className="mb-1 block font-semibold text-slate-200">
                  Reason / Reference Note
                </label>
                <input
                  type="text"
                  placeholder={
                    stockModalType === "IN"
                      ? "e.g. Supplier PO #42 or workshop restock"
                      : "e.g. Project Tent #12 dispatch or workshop use"
                  }
                  value={stockModalReason}
                  onChange={(e) => setStockModalReason(e.target.value)}
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-white focus:border-blue-500 focus:outline-none"
                />
              </div>

              <div className="flex justify-end gap-2 pt-3 border-t border-slate-800">
                <button
                  type="button"
                  onClick={() => setStockModalType(null)}
                  className="rounded-lg border border-slate-700 bg-slate-800 px-4 py-2 font-semibold text-slate-300 hover:bg-slate-700"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={stockModalSubmitting}
                  className={`rounded-lg px-4 py-2 font-semibold text-white shadow-sm disabled:opacity-50 ${
                    stockModalType === "IN" ? "bg-emerald-600 hover:bg-emerald-500" : "bg-amber-600 hover:bg-amber-500"
                  }`}
                >
                  {stockModalSubmitting ? (
                    <Loader2 size={14} className="animate-spin" />
                  ) : stockModalType === "IN" ? (
                    "Confirm Stock In"
                  ) : (
                    "Confirm Stock Out"
                  )}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </main>
  );
}
